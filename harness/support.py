"""DNS scope, baseline and hook helpers."""

from collections import Counter
import json
import shlex
import time

WRITABLE_TYPES = {"A", "AAAA", "CAA", "CNAME", "MX", "SRV", "TXT"}
GENERATED_DNSSEC_TYPES = {"RRSIG", "NSEC", "NSEC3"}


def owns_name(name, domain):
    name = name.rstrip(".").lower()
    return name == domain or name.endswith("." + domain)


def assert_preview_scope(result, domain, zone):
    for action in ("create", "update", "delete", "unchanged"):
        for record in result[action]:
            name = record["name"].rstrip(".")
            absolute = zone if name == "@" else name + "." + zone
            if not owns_name(absolute, domain):
                raise RuntimeError(
                    "Preview contains a record outside the temporary namespace"
                )


def hook_source(domain, state):
    # YunoHost explicitly invokes extensionless hooks with /bin/bash, regardless
    # of their shebang. JSON is accepted by its YAML return-value parser.
    return (
        "#!/bin/bash\nset -euo pipefail\n"
        f'if [[ "${{base_domain:-}}" == {shlex.quote(domain)} ]]; then\n'
        f'    cat -- {shlex.quote(str(state))} > "$YNH_STDRETURN"\n'
        'else\n    printf "[]\\n" > "$YNH_STDRETURN"\nfi\n'
    )


def baseline_fingerprints(rows):
    import dns.rdata

    result = Counter()
    for record in rows:
        # Signatures/denial-of-existence chains are generated by the authority.
        if record["type"] in GENERATED_DNSSEC_TYPES:
            continue
        fields = {
            k: record.get(k) for k in ("name", "type", "content", "ttl", "options")
        }
        if record["type"] == "SOA":
            soa = dns.rdata.from_text("IN", "SOA", record["content"])
            fields["content"] = soa.replace(serial=0).to_text()
        result[json.dumps(fields, sort_keys=True)] += 1
    return result


def wait_read(read, condition, timeout=60):
    deadline = time.monotonic() + timeout
    while True:
        result = read()
        if condition(result):
            return result
        if time.monotonic() >= deadline:
            raise RuntimeError("Read-back did not converge before timeout")
        time.sleep(2)
